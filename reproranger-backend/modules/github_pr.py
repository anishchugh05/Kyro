"""
GitHub PR Creator — uses the GitHub Git Data API to:
  1. Create a new branch from the repo's default branch
  2. Commit the fixed files atomically (single clean commit)
  3. Open a Pull Request

Requires GITHUB_TOKEN with `repo` scope (write access to the target repo).
"""
from __future__ import annotations

import base64
import os
import re
from dataclasses import dataclass
from typing import List, Optional

import httpx

GITHUB_API = "https://api.github.com"
TIMEOUT = 30.0


@dataclass
class PullRequestResult:
    url: str
    number: int
    branch: str


def _parse_owner_repo(repo_url: str) -> tuple:
    """Extract (owner, repo) from any GitHub URL format."""
    url = repo_url.strip().rstrip("/").replace(".git", "")
    m = re.search(r"github\.com[/:]([^/\s]+)/([^/\s]+)", url)
    if m:
        return m.group(1), m.group(2)
    parts = [p for p in url.split("/") if p]
    if len(parts) >= 2:
        return parts[-2], parts[-1]
    raise ValueError(f"Cannot parse owner/repo from URL: {repo_url}")


def _headers(token: str) -> dict:
    return {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }


def create_pull_request_sync(
    repo_url: str,
    github_token: str,
    fixes: List[dict],       # [{file, new_content, explanation}]
    branch_name: str,
    pr_title: str,
    pr_body: str,
) -> PullRequestResult:
    """
    Synchronous implementation — call via run_in_executor in the async pipeline.
    Uses the Git Data API so we never need a local git push.
    """
    owner, repo = _parse_owner_repo(repo_url)
    hdrs = _headers(github_token)

    with httpx.Client(timeout=TIMEOUT) as client:
        # 1. Get repo default branch
        repo_resp = client.get(f"{GITHUB_API}/repos/{owner}/{repo}", headers=hdrs)
        repo_resp.raise_for_status()
        default_branch = repo_resp.json().get("default_branch", "main")

        # 2. Get the SHA of the tip of the default branch
        ref_resp = client.get(
            f"{GITHUB_API}/repos/{owner}/{repo}/git/ref/heads/{default_branch}",
            headers=hdrs,
        )
        ref_resp.raise_for_status()
        base_commit_sha = ref_resp.json()["object"]["sha"]

        # 3. Get the tree SHA from that commit
        commit_resp = client.get(
            f"{GITHUB_API}/repos/{owner}/{repo}/git/commits/{base_commit_sha}",
            headers=hdrs,
        )
        commit_resp.raise_for_status()
        base_tree_sha = commit_resp.json()["tree"]["sha"]

        # 4. Create blob objects for each fixed file
        tree_entries = []
        for fix in fixes:
            blob_resp = client.post(
                f"{GITHUB_API}/repos/{owner}/{repo}/git/blobs",
                headers=hdrs,
                json={
                    "content": base64.b64encode(
                        fix["new_content"].encode("utf-8")
                    ).decode("ascii"),
                    "encoding": "base64",
                },
            )
            blob_resp.raise_for_status()
            blob_sha = blob_resp.json()["sha"]
            tree_entries.append({
                "path": fix["file"],
                "mode": "100644",
                "type": "blob",
                "sha": blob_sha,
            })

        # 5. Create a new tree on top of the base tree
        tree_resp = client.post(
            f"{GITHUB_API}/repos/{owner}/{repo}/git/trees",
            headers=hdrs,
            json={"base_tree": base_tree_sha, "tree": tree_entries},
        )
        tree_resp.raise_for_status()
        new_tree_sha = tree_resp.json()["sha"]

        # 6. Create the commit
        commit_message = f"{pr_title}\n\nGenerated by Kyro 🤖"
        new_commit_resp = client.post(
            f"{GITHUB_API}/repos/{owner}/{repo}/git/commits",
            headers=hdrs,
            json={
                "message": commit_message,
                "tree": new_tree_sha,
                "parents": [base_commit_sha],
            },
        )
        new_commit_resp.raise_for_status()
        new_commit_sha = new_commit_resp.json()["sha"]

        # 7. Create the branch pointing to the new commit
        branch_resp = client.post(
            f"{GITHUB_API}/repos/{owner}/{repo}/git/refs",
            headers=hdrs,
            json={
                "ref": f"refs/heads/{branch_name}",
                "sha": new_commit_sha,
            },
        )
        # 422 = branch already exists — try with a suffix
        if branch_resp.status_code == 422:
            branch_name = f"{branch_name}-2"
            branch_resp = client.post(
                f"{GITHUB_API}/repos/{owner}/{repo}/git/refs",
                headers=hdrs,
                json={"ref": f"refs/heads/{branch_name}", "sha": new_commit_sha},
            )
        branch_resp.raise_for_status()

        # 8. Open the Pull Request
        pr_resp = client.post(
            f"{GITHUB_API}/repos/{owner}/{repo}/pulls",
            headers=hdrs,
            json={
                "title": pr_title,
                "body": pr_body,
                "head": branch_name,
                "base": default_branch,
            },
        )
        pr_resp.raise_for_status()
        pr_data = pr_resp.json()

        return PullRequestResult(
            url=pr_data["html_url"],
            number=pr_data["number"],
            branch=branch_name,
        )


def build_pr_body(issue_text: str, fixes: List[dict], full_diff: str) -> str:
    """Compose a markdown PR description."""
    explanations = "\n".join(
        f"- **{fix['file']}**: {fix.get('explanation', 'No explanation provided.')}"
        for fix in fixes
    )
    diff_block = f"```diff\n{full_diff[:4000]}\n```" if full_diff else ""

    # Build the issue section — if no explicit issue was provided, synthesise a
    # description from what the agent actually changed so the PR is self-explanatory.
    if issue_text.strip() and not issue_text.startswith("Repository-wide audit"):
        issue_block = "\n".join(f"> {line}" for line in issue_text.strip()[:600].splitlines())
    else:
        # Auto-audit mode: describe the fix in terms of what was changed
        if fixes:
            summary_lines = [
                f"Kyro performed an autonomous repository audit and identified the following issue(s):"
            ]
            for fix in fixes:
                explanation = fix.get("explanation", "")
                if explanation:
                    summary_lines.append(f"- **{fix['file']}**: {explanation}")
            issue_block = "\n".join(f"> {line}" for line in summary_lines)
        else:
            issue_block = "> Kyro performed a repository-wide audit."

    return (
        f"## 🤖 Kyro Automated Fix\n\n"
        f"**Issue analyzed:**\n{issue_block}\n\n"
        f"**Changes made:**\n{explanations}\n\n"
        f"<details>\n<summary>Unified Diff</summary>\n\n{diff_block}\n\n</details>\n\n"
        f"---\n_Generated by [Kyro](https://github.com) — autonomous AI engineer_"
    )
